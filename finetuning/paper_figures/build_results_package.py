# Generated by the notebook; not covered by the checksums, so a rerun does not invalidate them.
GENERATED = ("figures/", "rebuilt_tables/", "logs/")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def wanted(path: Path) -> bool:
    name = path.name
    return (path.suffix.lower() in KEEP_SUFFIXES and name not in SKIP_NAMES
            and not name.startswith(SKIP_PREFIXES))


class Copier:
    def __init__(self, dest: Path, log):
        self.dest, self.log, self.files, self.bytes = dest, log, 0, 0

    def file(self, src: Path, rel: str):
        target = self.dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, target)
        self.files += 1
        self.bytes += target.stat().st_size

    def tree(self, src: Path, rel: str):
        if not src.is_dir():
            raise SystemExit(f"Missing source folder: {src}")
        n0, b0 = self.files, self.bytes
        for base, dirs, files in os.walk(src):
            dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and "__pilot_" not in d)
            for name in sorted(files):
                p = Path(base, name)
                if wanted(p):
                    self.file(p, f"{rel}/{p.relative_to(src).as_posix()}")
        self.log(f"  {rel:42s} {self.files - n0:6d} files {(self.bytes - b0) / 1e6:8.1f} MB")


