"""Collect every result of the paper revision into one folder that can be shared.

Read-only on every source. Writes only to D:/Afterimage_data_share/afterimage_results_<date>/ (and, with --zip, its zip).

The folder holds, for every run: the logs, the training histories, the per-image predictions, the metric
summaries, the timing and energy records; plus the analysis code, the input label files, the analysis tables,
the figures notebook and a plain-text README. It holds no model weights, no checkpoints and no fundus images, so it
stays small enough to share. The figures notebook inside it rebuilds every table from the run records and draws
every figure, with nothing outside the folder.

Usage (from the repo root, CPU only):
  python -I -B finetuning/paper_figures/build_results_package.py                     # build the folder
  python -I -B finetuning/paper_figures/build_results_package.py --add report.pdf    # ... with extra top-level files
  python -I -B finetuning/paper_figures/build_results_package.py --zip               # optional: zip a finished folder
"""
