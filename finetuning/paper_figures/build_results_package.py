def build(dest: Path, extras: list[Path]) -> None:
    if dest.exists():
        raise SystemExit(f"{dest} already exists. Pick another --name; this script never overwrites a package.")
    for p in [NOTEBOOK, TABLES / "per_run_metrics.csv", MESSIDOR2 / "02_adjudicated_grades" / "messidor_data.csv", *extras]:
        if not p.is_file():
            raise SystemExit(f"Missing: {p}")
    dest.mkdir(parents=True)
    (dest / "logs").mkdir()
    log_path = dest / "logs" / "build_package.log"
    lines: list[str] = []

    def log(msg: str):
        print(msg)
        lines.append(msg)
        log_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    commit = subprocess.run(["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    log(f"Building {dest} at {datetime.now():%Y-%m-%d %H:%M:%S} from repo commit {commit}")
    c = Copier(dest, log)

    log("Run records (text only: logs, histories, predictions, summaries):")
    for folder in EXPERIMENT_FOLDERS:
        c.tree(EXPERIMENTS / folder, f"experiments/{folder}")
    for p in sorted(EXPERIMENTS.iterdir()):
        if p.is_file() and wanted(p):
            c.file(p, f"experiments/{p.name}")

    log("The 17 November evidence pack and its workbooks:")
    c.tree(EVIDENCE / "evidence", "evidence_2026-11-17")
    for p in sorted(EVIDENCE.glob("*.xlsx")):
        c.file(p, f"evidence_2026-11-17/{p.name}")

    log("Experiment code and records from the repository (Markdown left out):")
    tracked = subprocess.run(["git", "-C", str(REPO), "ls-files", *REPO_FOLDERS],
                             capture_output=True, text=True, check=True).stdout.splitlines()
    n0 = c.files
    for rel in tracked:
        p = REPO / rel
        if p.is_file() and wanted(p) and not rel.startswith("finetuning/paper_tables/"):
            c.file(p, f"code/repo/{rel}")
    log(f"  code/repo (tracked files)                     {c.files - n0:6d} files")
    for rel in REPO_UNTRACKED:
        c.tree(REPO / rel, f"code/repo/{rel}")

    log("Analysis code and the committed tables it checks against:")
    pt = REPO / "finetuning" / "paper_tables"
    for name in CODE_FILES:
        c.file(pt / name, f"code/paper_tables/{name}")
    tracked = subprocess.run(["git", "-C", str(REPO), "ls-files", "finetuning/paper_tables/output"],
                             capture_output=True, text=True, check=True).stdout.split()
    for rel in tracked:
        if "/revision_analysis/" not in rel and not rel.endswith(".md"):
            c.file(REPO / rel, "code/paper_tables/" + rel.split("finetuning/paper_tables/", 1)[1])
    log(f"  code/paper_tables: {sum(1 for _ in (dest / 'code').rglob('*') if _.is_file())} files")

    log("Inputs:")
    c.file(MESSIDOR2 / "02_adjudicated_grades" / "messidor_data.csv", "inputs/messidor2/messidor_data.csv")
    c.file(MESSIDOR2 / "03_eye_pairing" / "pairs.csv", "inputs/messidor2/pairs.csv")
    for name in ("messidor_duplicate_pairs.csv", "near_duplicate_test_ids.csv"):
        c.file(TABLES / "image_audits" / name, f"inputs/image_audits/{name}")

    log("Tables as built in the repository (CSV and JSON; no SUMMARY.md):")
    c.tree(TABLES, "tables")
    # The image-quality error analysis reads the fundus images, which the package leaves out, so it ships as results.
    errors = REPO / "finetuning" / "paper_tables" / "output" / "error_analysis"
    if errors.is_dir():
        c.tree(errors, "tables/error_analysis")

    log("Notebook and extra files:")
    c.file(NOTEBOOK, NOTEBOOK.name)
    for p in extras:
        c.file(p, p.name)

    counts = (f"{c.files:,} files, {c.bytes / 1e6:,.1f} MB before the notebook runs; "
              f"{sum(1 for _ in (dest / 'experiments').rglob('train_result.json')):,} training records and "
              f"{sum(1 for _ in (dest / 'experiments').rglob('*predictions.csv')):,} prediction files.")
    notes = ["Read this first."] + ["Companion document."] * (len(extras) - 1)
    extra_lines = "".join(f"{p.name}\n{'':27s}{note}\n" if len(p.name) > 26 else f"{p.name:<27s}{note}\n"
                          for p, note in zip(extras, notes))
    (dest / "README.txt").write_text(README.format(built=f"{date.today():%d %B %Y}", commit=commit, n_figures="25",
                                                   counts=counts, extras=extra_lines), encoding="utf-8")
    too_long = [rel for rel, _ in c.sources if len(rel) > MAX_RELATIVE_PATH]
    if too_long:
        raise SystemExit(f"{len(too_long)} paths exceed {MAX_RELATIVE_PATH} characters, e.g. {too_long[0]}")
    log(f"Longest path inside the package: {max(len(rel) for rel, _ in c.sources)} characters")
    # Where every file came from, as in the 17 November evidence pack.
    with (dest / "MANIFEST.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["relative_path", "source_path", "bytes", "sha256"])
        for rel, src in sorted(c.sources):
            target = dest / rel
            w.writerow([rel, str(src), target.stat().st_size, sha256(target)])
    write_checksums(dest)
    log(f"Done: {c.files:,} files, {c.bytes / 1e6:,.1f} MB. Next: run the notebook in the folder.")


def write_checksums(dest: Path) -> None:
    rows = []
    for p in sorted(dest.rglob("*")):
        rel = p.relative_to(dest).as_posix()
        if p.is_file() and rel != "SHA256SUMS.txt" and not rel.startswith(GENERATED):
            rows.append(f"{sha256(p)}  {rel}")
    (dest / "SHA256SUMS.txt").write_text("\n".join(rows) + "\n", encoding="utf-8")


def make_zip(dest: Path) -> None:
    if not (dest / "figures" / "figure_index.csv").is_file():
        raise SystemExit("Run the notebook in the package first, so the zip carries the figures.")
    archive = dest.with_suffix(".zip")
    if archive.exists():
        raise SystemExit(f"{archive} already exists.")
    files = sorted(p for p in dest.rglob("*") if p.is_file())
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for p in files:
            # No extra top folder: Windows "Extract All" already creates one named after the zip.
            zf.write(p, p.relative_to(dest).as_posix())
    with zipfile.ZipFile(archive) as zf:
        bad = zf.testzip()
        if bad or len(zf.namelist()) != len(files):
            raise SystemExit(f"Zip check failed: {bad or 'file count differs'}")
    digest = sha256(archive)
    size = archive.stat().st_size
    sums = SHARE / "SHA256SUMS.txt"
    sums.write_text(sums.read_text(encoding="utf-8").rstrip("\n") + f"\n{digest}  {archive.name}\n", encoding="utf-8")
    readme = SHARE / "README.txt"
    readme.write_text(readme.read_text(encoding="utf-8").rstrip("\n") + (
        f"\n\n{archive.name}\n  {len(files)} files, {size:,} bytes\n  sha256 {digest}\n"
        f"  all revision results in one folder: run logs, training histories, predictions, tables, figures,\n"
        f"  documents and make_paper_figures.ipynb, which rebuilds the tables and figures.\n"
        f"  Extract All to a short location (Downloads or D:\\); see README.txt inside.\n"), encoding="utf-8")
    print(f"{archive}: {len(files)} files, {size / 2**20:.1f} MiB, sha256 {digest}")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--name", default=f"afterimage_results_{date.today():%Y%m%d}")
    parser.add_argument("--add", nargs="*", default=[], type=Path, help="extra files to put at the top of the folder")
    parser.add_argument("--zip", action="store_true", help="zip a finished package folder and add it to the share README")
    args = parser.parse_args(argv)
    dest = SHARE / args.name
    if args.zip:
        make_zip(dest)
    else:
        build(dest, [p.resolve() for p in args.add])
    return 0


if __name__ == "__main__":
    sys.exit(main())
