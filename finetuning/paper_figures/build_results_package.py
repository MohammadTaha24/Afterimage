SHARE = Path(r"D:\Afterimage_data_share")
TABLES = REPO / "finetuning" / "paper_tables" / "output" / "revision_analysis"

# Everything in the experiments folder, keeping its layout so the analysis code reads it unchanged: every run and
# campaign including the pilots, the dataset manifests, queue logs and checks, the launcher notebooks and code, the
# model-asset metadata (no weights) and the 17 November evidence pack with its two workbooks.
EXPERIMENT_FOLDERS = ["runs", "final_runs", "retizero_runs", "reference", "datasets", "logs", "checks", "code",
                      "assets"]
# The 17 November evidence pack goes at the top of the package, one level shallower, so its deepest paths stay
# inside the Windows 260-character limit when the zip is extracted.
EVIDENCE = EXPERIMENTS / "deliverables_2026-11-17"
MAX_RELATIVE_PATH = 180   # leaves 80 characters for the folder the zip is extracted into
# Experiment code and records kept in the repository: every tracked file under these folders (Markdown excepted),
# plus the git-ignored original-split runs and replay of the archived adapter.
REPO_FOLDERS = ["finetuning", "external"]
REPO_UNTRACKED = ["finetuning/Qwen3/artifacts/paper_reproduction"]
# No Markdown: run_report.md, the queue summary.md files and the library-written checkpoint README.md files repeat
# what the JSON and CSV records already hold. No weights, checkpoints, images or archives.
KEEP_SUFFIXES = {".csv", ".json", ".jsonl", ".log", ".txt", ".py", ".ipynb", ".xlsx"}
SKIP_DIRS = {"cache", "dataset_cache", "best_lora", "__pycache__", ".locks", "temp", "tmp", "hub", "xet", "images"}
SKIP_NAMES = {"tokenizer.json", "tokenizer_config.json", "processor_config.json", "vocab.json", "merges.txt"}
SKIP_PREFIXES = ("protected_files_",)   # 50 MB file-hash snapshots used only by the GPU queue's integrity check

CODE_FILES = ["build_revision_analysis.py", "build_paper_tables.py", "build_image_audits.py",
              "build_efficiency_tables.py", "build_error_analysis.py"]
NOTEBOOK = REPO / "finetuning" / "paper_figures" / "make_paper_figures.ipynb"
# Generated by the notebook; not covered by the checksums, so a rerun does not invalidate them.
GENERATED = ("figures/", "rebuilt_tables/", "logs/")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def wanted(path: Path) -> bool:
    name = path.name
    return (path.suffix.lower() in KEEP_SUFFIXES and name not in SKIP_NAMES
            and not name.startswith(SKIP_PREFIXES))


class Copier:
    def __init__(self, dest: Path, log):
        self.dest, self.log, self.files, self.bytes = dest, log, 0, 0
        self.sources: list[tuple[str, Path]] = []   # (published path, source path) for MANIFEST.csv

    def file(self, src: Path, rel: str):
        target = self.dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, target)
        self.files += 1
        self.bytes += target.stat().st_size
        self.sources.append((rel, src))

    def tree(self, src: Path, rel: str):
        if not src.is_dir():
            raise SystemExit(f"Missing source folder: {src}")
        n0, b0 = self.files, self.bytes
        for base, dirs, files in os.walk(src):
            dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
            for name in sorted(files):
                p = Path(base, name)
                if wanted(p):
                    self.file(p, f"{rel}/{p.relative_to(src).as_posix()}")
        self.log(f"  {rel:42s} {self.files - n0:6d} files {(self.bytes - b0) / 1e6:8.1f} MB")


